const {test}=require('node:test'),assert=require('node:assert/strict');
const {spawn}=require('node:child_process'),dgram=require('node:dgram'),path=require('node:path');
const {WebSocketServer}=require('../node_modules/ws');
const {decodeOSC}=require('../com.personal.abletondeck.sdPlugin/shared.cjs');
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
test('actual plugin process registers, renders audio, sends commands and resets Max',async()=>{
  const server=new WebSocketServer({host:'127.0.0.1',port:0});
  await new Promise(resolve=>server.once('listening',resolve));
  const control=dgram.createSocket('udp4'),max=dgram.createSocket('udp4'),source=dgram.createSocket('udp4');
  const portBase=23940;
  await new Promise(resolve=>control.bind(portBase,'127.0.0.1',resolve));
  await new Promise(resolve=>max.bind(portBase+2,'127.0.0.1',resolve));
  const connected=new Promise(resolve=>server.once('connection',resolve));
  const process_=spawn(process.execPath,[path.join(__dirname,'../com.personal.abletondeck.sdPlugin/plugin.cjs'),'-port',String(server.address().port),'-pluginUUID','test-uuid','-registerEvent','registerPlugin'],{stdio:'pipe',env:{...process.env,ABLETONDECK_TEST_PORT_BASE:String(portBase)}});
  const messages=[];
  let ws;
  try {
    ws=await connected;
    ws.on('message',b=>messages.push(JSON.parse(b.toString())));
    await delay(100);
    assert.ok(messages.some(m=>m.event==='registerPlugin'&&m.uuid==='test-uuid'));
    const emit=(event,kind,payload={})=>ws.send(JSON.stringify({event,context:kind,action:'com.personal.abletondeck.'+kind,payload}));
    emit('willAppear','play',{settings:{}});emit('willAppear','lufs',{settings:{}});
    source.send(Buffer.from(JSON.stringify({v:1,type:'state',playing:false,tempo:120,track:{name:'Drums'}})),portBase+1,'127.0.0.1');
    const oscStr=s=>{const b=Buffer.from(s+'\0');return Buffer.concat([b,Buffer.alloc((4-b.length%4)%4)])};
    const floats=Buffer.alloc(14*4);[-12.4,-13.2,-14.1,-1.2,-0.8,0,...Array(8).fill(-25)].forEach((v,j)=>floats.writeFloatBE(v,j*4));
    const packet=Buffer.concat([oscStr('/yfc/meter'),oscStr(','+'f'.repeat(14)),floats]);
    source.send(packet,portBase+1,'127.0.0.1');await delay(150);
    const image=messages.filter(m=>m.event==='setImage'&&m.context==='lufs').at(-1);
    assert.match(Buffer.from(image.payload.image.split(',')[1],'base64').toString(),/-13.2/);
    const cmd=new Promise(resolve=>control.once('message',b=>resolve(JSON.parse(b.toString()))));
    emit('keyDown','play');emit('keyUp','play');
    assert.equal((await cmd).command,'play');
    const reset=new Promise(resolve=>max.once('message',b=>resolve(decodeOSC(b))));
    emit('keyDown','lufs');await delay(700);emit('keyUp','lufs');
    assert.equal((await reset).address,'/yfc/reset');
    emit('keyDown','lufs');emit('keyUp','lufs');await delay(50);
    assert.ok(messages.some(m=>m.event==='setSettings'&&m.payload.mode==='m'));
    const sendOSC=(address,values)=>{
      const data=Buffer.alloc(values.length*4);values.forEach((v,j)=>data.writeFloatBE(v,j*4));
      source.send(Buffer.concat([oscStr(address),oscStr(','+'f'.repeat(values.length)),data]),portBase+1,'127.0.0.1');
    };
    for(const kind of ['midside','waveform','vectorscope','goniometer'])emit('willAppear',kind,{settings:{}});
    sendOSC('/yfc/meter',[-12,-13,-14,-1,-1,0,...Array(8).fill(-25),0.75,0.25]);
    sendOSC('/yfc/scope',[20,...Array.from({length:128},(_,j)=>[Math.sin(j/8)*0.3,Math.cos(j/8)*0.3]).flat(),...Array.from({length:64},()=>[-0.3,0.3,-0.3,0.3]).flat()]);
    await delay(150);
    const svg=kind=>Buffer.from(messages.filter(m=>m.event==='setImage'&&m.context===kind).at(-1).payload.image.split(',')[1],'base64').toString();
    for(const kind of ['pitch','reactive'])emit('willAppear',kind,{settings:{}});
    const pitchSamples=Array.from({length:1080},(_,j)=>.3*Math.sin(2*Math.PI*55*j/12000));
    sendOSC('/yfc/pitchchunk',[1,12000,600,1080,...pitchSamples.slice(600)]);
    sendOSC('/yfc/pitchchunk',[1,12000,0,1080,...pitchSamples.slice(0,600)]);await delay(150);
    assert.match(svg('pitch'),/data-pitch="A1"/);
    const waveBefore=svg('waveform');
    const changedSamples=pitchSamples.map((v,j)=>v+.12*Math.sin(4*Math.PI*55*j/12000));
    sendOSC('/yfc/pitchchunk',[2,12000,0,1080,...changedSamples.slice(0,600)]);
    sendOSC('/yfc/pitchchunk',[2,12000,600,1080,...changedSamples.slice(600)]);
    await delay(40);
    assert.notEqual(svg('waveform'),waveBefore,'next raw capture updates the scope promptly');
    assert.match(svg('reactive'),/data-reactive="true"/);
    for(const visualStyle of ['ribbon','field','mesh','particles']){
      emit('didReceiveSettings','reactive',{settings:{visualStyle}});await delay(100);
      assert.match(svg('reactive'),new RegExp(`data-style="${visualStyle==='particles'?'flow':visualStyle}"`));
    }
    emit('keyDown','reactive');emit('keyUp','reactive');await delay(80);
    const frozenReactive=svg('reactive');await delay(100);assert.equal(svg('reactive'),frozenReactive);
    emit('keyDown','reactive');emit('keyUp','reactive');await delay(80);
    assert.match(svg('midside'),/data-mid="75"/);
    for(const kind of ['waveform','vectorscope','goniometer'])assert.match(svg(kind),/<path|<circle/);
    emit('keyDown','midside');emit('keyUp','midside');await delay(100);
    assert.match(svg('midside'),/data-frozen="true"/);
    sendOSC('/yfc/meter',[-12,-13,-14,-1,-1,0,...Array(8).fill(-25),0.25,0.75]);await delay(100);
    assert.match(svg('midside'),/data-mid="75"/);
    for(let j=1;j<=5;j++)emit('willAppear','spectrum'+j,{settings:{}});
    sendOSC('/yfc/spectrum',Array(60).fill(-30));await delay(150);
    for(let j=1;j<=5;j++)assert.match(svg('spectrum'+j),/data-spectrum="contour"/);
    emit('keyDown','spectrum1');emit('keyUp','spectrum1');await delay(80);
    const frozenImages=Array.from({length:5},(_,j)=>svg('spectrum'+(j+1)));
    frozenImages.forEach(v=>assert.match(v,/data-frozen="true"/));
    sendOSC('/yfc/spectrum',Array(60).fill(-60));await delay(100);
    assert.deepEqual(Array.from({length:5},(_,j)=>svg('spectrum'+(j+1))),frozenImages);
    emit('keyDown','spectrum5');emit('keyUp','spectrum5');await delay(80);
    for(let j=1;j<=5;j++)assert.doesNotMatch(svg('spectrum'+j),/data-frozen="true"/);
    await delay(1850);
    assert.match(svg('lufs'),/data-value="0.0"/);
    assert.doesNotMatch(svg('pitch'),/data-pitch|data-idle/);
    assert.match(svg('midside'),/data-mid="75"/);
    assert.doesNotMatch(svg('waveform'),/data-idle/);
    assert.match(svg('spectrum1'),/data-spectrum="silence"/);
    emit('keyDown','midside');emit('keyUp','midside');await delay(100);
    assert.match(svg('midside'),/data-value="0.0"/);
    sendOSC('/yfc/meter',[-100,-80,-14,-120,-1,0,...Array(8).fill(-120),0,0]);await delay(100);
    assert.match(svg('lufs'),/data-value="0.0"/);
    assert.doesNotMatch(svg('lufs'),/data-idle/);
    sendOSC('/yfc/meter',[-12,-13,-14,-1,-1,0,...Array(8).fill(-25),0.75,0.25]);await delay(200);
    assert.match(svg('lufs'),/data-value="-12.0"/);
    emit('willAppear','spectrogram',{settings:{}});
    const fftSamples=Array.from({length:16384*2},(_,j)=>.1*Math.sin(2*Math.PI*1000*Math.floor(j/2)/48000));
    for(let offset=0;offset<fftSamples.length;offset+=600)sendOSC('/yfc/fftchunk',[1,48000,offset,16384,...fftSamples.slice(offset,offset+600)]);
    await delay(200);
    assert.match(svg('spectrum3'),/frequency-peak/);
    assert.match(svg('spectrum3'),/1000 Hz/);
    assert.match(svg('spectrogram'),/data-spectrogram/);
    emit('keyDown','spectrogram');emit('keyUp','spectrogram');await delay(80);
    const frozenSpectrogram=svg('spectrogram');await delay(150);assert.equal(svg('spectrogram'),frozenSpectrogram);
    emit('keyDown','spectrogram');emit('keyUp','spectrogram');await delay(80);assert.doesNotMatch(svg('spectrogram'),/data-frozen/);
    for(const session of [100,200]){
      const hz=session===100?1000:2000;
      const samples=Array.from({length:16384*2},(_,j)=>.1*Math.sin(2*Math.PI*hz*Math.floor(j/2)/48000));
      for(let offset=0;offset<samples.length;offset+=600)sendOSC('/yfc/fftchunk2',[session,1,48000,offset,16384,...samples.slice(offset,offset+600)]);
      await delay(160);
      assert.match(svg(session===100?'spectrum3':'spectrum4'),new RegExp(hz+' Hz'),'actual plugin accepts a new meter with the same frame number');
    }
    // Exercise the real plugin/inspector message path, not just palette helpers.
    emit('didReceiveSettings','lufs',{settings:{theme:'red'}});
    emit('sendToPlugin','reactive',{type:'appearance',settings:{theme:'green',performance:'smooth'}});
    await delay(150);
    assert.ok(messages.some(m=>m.event==='setGlobalSettings'&&m.payload.theme==='green'));
    assert.match(svg('reactive'),/#23f278/);
    assert.match(svg('lufs'),/data-value=.*fill="#ffffff"/);
    emit('willAppear','theme',{settings:{}});await delay(80);
    emit('keyDown','theme');emit('keyUp','theme');await delay(100);
    assert.ok(messages.some(m=>m.event==='setGlobalSettings'&&m.payload.theme==='blue'));
    assert.match(svg('theme'),/#237cf2/);
    emit('didReceiveGlobalSettings','theme',{settings:{theme:'purple',performance:'smooth'}});await delay(100);
    assert.match(svg('reactive'),/#da23f2/);
    const frameCount=()=>messages.filter(m=>m.event==='setImage'&&m.context==='reactive').length;
    let start=frameCount();await delay(600);const smoothFrames=frameCount()-start;
    emit('sendToPlugin','reactive',{type:'appearance',settings:{theme:'purple',performance:'economy'}});await delay(100);
    start=frameCount();await delay(600);const ecoFrames=frameCount()-start;
    assert.ok(ecoFrames<smoothFrames,`${ecoFrames} economy vs ${smoothFrames} smooth frames`);
    assert.ok(ecoFrames<=7,'economy reactive frame budget');
    assert.match(svg('reactive'),/width="72" height="72"/);
  } finally {
    process_.kill();if(ws)ws.terminate();await new Promise(resolve=>server.close(resolve));
    control.close();max.close();source.close();
  }
});
